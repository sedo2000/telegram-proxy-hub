create table if not exists public.users (
  telegram_id bigint primary key,
  username text,
  first_name text,
  last_name text,
  created_at timestamptz not null default now(),
  last_seen_at timestamptz not null default now()
);

create table if not exists public.proxies (
  id bigint generated by default as identity primary key,
  proxy_key text not null unique,
  type text not null default 'socks5',
  host text not null,
  port integer not null check (port between 1 and 65535),
  secret text,
  latency_ms integer not null check (latency_ms >= 0),
  checked_at timestamptz not null default now(),
  published_at timestamptz,
  active boolean not null default true
);

-- Upgrade existing SOCKS5 installations to support MTProto hostnames and secrets.
alter table public.proxies alter column host type text using host::text;
alter table public.proxies add column if not exists secret text;

create index if not exists proxies_active_latency_idx
  on public.proxies (active, latency_ms asc);

alter table public.users enable row level security;
alter table public.proxies enable row level security;

-- The application uses the Supabase service-role key only in Vercel server-side functions.
-- Do not expose this key in a browser, mobile app, or public repository.

 
create index if not exists proxies_mtproto_active_latency_idx
  on public.proxies (latency_ms asc)
  where active = true and type = 'mtproto' and secret is not null;

create table if not exists public.favorites (
  telegram_id bigint not null references public.users(telegram_id) on delete cascade,
  proxy_key text not null references public.proxies(proxy_key) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (telegram_id, proxy_key)
);
alter table public.favorites enable row level security;
